export function generateAiPolicy(opts) {
  const optout = opts.training_optout === 'yes';
  const prohibited = opts.ai_usage === 'prohibited';

  let md = `# AI Policy

## Accountability

You are responsible for every line of code you submit, regardless of how it was produced.`;
  if (!prohibited) md += ` If you use AI tools, review and verify all output before committing. An agent opens a pull request or issue only at a person's request, and that person answers for it.`;
  md += `

## AI Tool Usage

`;

  if (opts.ai_usage === 'permitted') {
    md += `AI tools are permitted for code generation, review, and documentation.\n\n`;
  } else if (opts.ai_usage === 'permitted-with-review') {
    md += `AI tools are permitted. Standard review process applies to all contributions.\n\n`;
  } else if (opts.ai_usage === 'restricted') {
    md += `AI tool usage is restricted. Get maintainer approval before using AI tools on contributions.\n\n`;
  } else {
    md += `AI tools are not permitted for contributions to this project. All contributions must be human-authored.\n\n`;
  }

  md += `## AI-Generated Code\n\n`;

  if (prohibited) {
    md += `AI-generated code is not accepted.\n\n`;
  } else if (opts.ai_code === 'accepted') {
    md += `AI-generated code is accepted under the standard contribution workflow.\n\n`;
  } else if (opts.ai_code === 'requires-review') {
    md += `AI-generated code must be reviewed by a human maintainer before merging. Keep changes atomic. You must be able to explain any line on request.\n\n`;
  } else if (opts.ai_code === 'requires-attribution') {
    md += `AI-generated code must be attributed. Use a commit trailer:\n\n\`\`\`text\nAssisted-by: <tool name>\n\`\`\`\n\nPull requests should note which portions were AI-generated.\n\n`;
  } else {
    md += `AI-generated code is not accepted.\n\n`;
  }

  // Disclosure (skip if requires-attribution already shows the trailer)
  if (prohibited || opts.ai_code === 'requires-attribution') {
    // prohibited: nothing to disclose; requires-attribution: trailer shown above
  } else if (opts.disclosure === 'required' && opts.ai_code === 'not-accepted') {
    md += `## Disclosure\n\nIf AI tools were used in any capacity (research, debugging, understanding code), note it in the commit message:\n\n\`\`\`text\nAssisted-by: <tool name>\n\`\`\`\n\n`;
  } else if (opts.disclosure === 'required') {
    md += `## Disclosure\n\nMark AI involvement in commit messages with a trailer:\n\n\`\`\`text\nAssisted-by: <tool name>\n\`\`\`\n\n`;
  } else if (opts.disclosure === 'encouraged') {
    md += `## Disclosure\n\nWe encourage marking AI involvement in commit messages:\n\n\`\`\`text\nAssisted-by: <tool name>\n\`\`\`\n\nThis helps the project understand tooling patterns.\n\n`;
  }

  // Prohibited uses for non-open presets
  if (opts.ai_usage !== 'permitted' && !prohibited) {
    md += `## Prohibited Uses\n\n`;
    md += `- Submitting AI output you have not read and understood\n`;
    md += `- Using AI to generate code that circumvents tests or CI checks\n`;
    md += `- Feeding reviewer feedback back into AI without understanding it first\n`;
    if (opts.ai_usage === 'permitted-with-review') {
      md += `- AI-generated PR descriptions: describe your own work\n`;
      md += `- AI-generated review comments on other contributors' PRs\n`;
    }
    md += `\n`;
  }

  md += `## AI in CI/CD\n\n`;

  if (opts.ai_cicd === 'permitted') {
    md += `AI tools may be used in CI/CD pipelines for code analysis and test generation.\n\n`;
  } else if (opts.ai_cicd === 'restricted') {
    md += `AI tools in CI/CD pipelines require explicit maintainer approval.\n\n`;
  } else {
    md += `AI tools are not permitted in CI/CD pipelines. All automation must use deterministic, non-AI tooling.\n\n`;
  }

  md += `## Training Data\n\n`;

  if (optout) {
    md += `This project requests that its code not be used for AI model training. We ask that AI tool providers honor this preference.\n\n`;
  } else {
    md += `This project does not opt out of AI training data collection. Standard platform terms apply.\n\n`;
  }

  // Licensing -- only when AI code is accepted in some form
  if (opts.ai_code !== 'not-accepted' && !prohibited) {
    md += `## Licensing\n\nAI-generated contributions must be compatible with this project's license. Confirm your AI tool's terms place no restriction on its output that conflicts with this license. Do not submit AI output that includes third-party material unless its license permits the contribution and you keep its notice and attribution. Contributors must be able to certify their submissions under the project's contribution terms.\n\n`;
  }

  // Enforcement for non-open presets
  if (opts.ai_usage !== 'permitted') {
    md += `## Enforcement\n\n`;
    if (prohibited) {
      md += `Maintainers may close AI-generated PRs without detailed feedback.\n\n`;
    } else if (opts.ai_usage === 'restricted') {
      md += `Maintainers may close AI-generated PRs without detailed feedback. Repeated low-quality AI submissions may result in the contributor being asked to stop using AI tools for contributions.\n\n`;
    } else {
      md += `Maintainers may close AI-generated PRs that do not meet these standards without detailed feedback.\n\n`;
    }
  }

  md += `## Policy Evolution\n\nThis policy will evolve as tooling and conventions change. Contributions to the policy itself are welcome.\n`;

  md += FOOTER;
  return md;
}

// Tool files only. generateAiPolicy handles requires-attribution in its own branch.
const disclosureOf = (o) => (o.ai_code === 'requires-attribution' ? 'required' : o.disclosure);

export function generateAgents(opts) {
  let md = `# Agents

`;
  if (opts.ai_usage === 'prohibited') return md + PROHIBITED + FOOTER;

  if (opts.ai_code === 'not-accepted') {
    md += `Rules for AI coding agents assisting with this repository. ${NOT_ACCEPTED_SCOPE}\n`;
  } else {
    md += `Rules for AI coding agents working in this repository.\n`;
  }

  md += `
## General

- Follow existing code conventions and patterns
- Do not modify files outside the scope of the current task
- Prefer editing existing files over creating new ones
- Do not add dependencies without explicit approval
`;

  if (opts.ai_usage === 'permitted') {
    md += `- Ask for clarification when requirements are ambiguous\n`;
  } else if (opts.ai_usage === 'restricted') {
    md += restrictedRules();
  } else {
    md += `- Ask for clarification when requirements are ambiguous\n`;
    md += `- Do not generate PR descriptions or review comments on others' code\n`;
  }
  md += generalRules();

  md += codeStyleSection(opts.code_style);

  md += `
## Setup

<!-- Add your project's setup commands here (npm install, go build, make, etc.) -->

## Testing

`;

  if (opts.test_reqs === 'none') {
    md += `Follow the project's existing testing conventions.\n`;
  } else if (opts.test_reqs === 'recommended') {
    md += `Write tests for new functionality. Run the full suite before submitting.\n`;
  } else {
    md += `Tests are required. Run the full test suite before submitting. PRs without adequate test coverage will not be merged.\n`;
  }

  const paths = pathList(opts.restricted_paths);
  if (paths.length) {
    md += `\n## Restricted Paths\n\n${RESTRICTED_PATHS_LEAD}\n\n`;
    for (const p of paths) {
      md += `- \`${p}\`\n`;
    }
  }

  md += `
## Commits

- Use clear, descriptive commit messages
- One logical change per commit
- Reference relevant issues when applicable
`;

  if (disclosureOf(opts) === 'required') {
    md += `- Include \`Assisted-by: <tool name>\` trailer on AI-assisted commits\n`;
  } else if (disclosureOf(opts) === 'encouraged') {
    md += `- Consider adding \`Assisted-by: <tool name>\` trailer on AI-assisted commits\n`;
  }

  if (opts.review_reqs === 'significant-changes') {
    md += `\n## Review\n\nChanges touching more than one module or any security-relevant code require human review.\n`;
  } else if (opts.review_reqs === 'all-ai-prs') {
    md += `\n## Review\n\nAll pull requests require human review before merging, regardless of scope.\n`;
  }

  md += FOOTER;
  return md;
}

