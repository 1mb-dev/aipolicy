export const FOOTER = '\n---\n*Generated by [aipolicy.1mb.dev](https://aipolicy.1mb.dev)*\n';

// code_style and restricted_paths arrive raw from URL params: a newline, fence or heading
// in one must not start new structure in the generated file. Invisible characters (Unicode
// Cf and Default_Ignorable_Code_Point) are deleted, not spaced, so the preview shows what an
// agent reads. ZWNJ and ZWJ stay: Persian, Indic and emoji text need them between characters.
const INVISIBLE = /(?:(?![\u200C\u200D])[\p{Cf}\p{Default_Ignorable_Code_Point}])+/gu;
const oneLine = (s) => String(s ?? '').replace(INVISIBLE, '').replace(/[\p{Cc}\p{Zl}\p{Zp}\s]+/gu, ' ')
  .replace(/^[ \u200C\u200D]+|[ \u200C\u200D]+$/gu, '');
const fenceFor = (s) => '`'.repeat((s.match(/`+/g) ?? []).reduce((n, run) => Math.max(n, run.length + 1), 3));
const codeStyleSection = (s) => {
  const v = oneLine(s);
  if (!v) return '';
  const f = fenceFor(v);
  return `\n## Code Style\n\n${f}text\n${v}\n${f}\n`;
};
const pathList = (s) => String(s ?? '').split(',').map((p) => oneLine(p.replace(/`/g, ''))).filter(Boolean);

